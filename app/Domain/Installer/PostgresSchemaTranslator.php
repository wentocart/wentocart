<?php

namespace App\Domain\Installer;

/**
 * Best-effort MySQL dump → PostgreSQL DDL for fresh installs.
 * Not a full dialect engine — covers the patterns in database/schema/mysql-schema.sql.
 */
final class PostgresSchemaTranslator
{
    public static function translate(string $mysqlSql): string
    {
        $sql = $mysqlSql;
        $sql = preg_replace('/^SET\s+NAMES\s+utf8mb4\s*;/mi', '', $sql) ?? $sql;
        $sql = preg_replace('/^SET\s+FOREIGN_KEY_CHECKS\s*=\s*\d+\s*;/mi', '', $sql) ?? $sql;
        $sql = preg_replace('/^SET\s+UNIQUE_CHECKS\s*=\s*\d+\s*;/mi', '', $sql) ?? $sql;
        $sql = preg_replace('/^SET\s+SQL_MODE\s*=\s*[^;]+;/mi', '', $sql) ?? $sql;

        $sql = preg_replace('/\bENGINE\s*=\s*\w+/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bDEFAULT\s+CHARSET\s*=\s*\w+/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bCOLLATE\s*=\s*[\w]+/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bCHARACTER\s+SET\s+\w+/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bCOLLATE\s+[\w]+/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bAUTO_INCREMENT\s*=\s*\d+/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bROW_FORMAT\s*=\s*\w+/i', '', $sql) ?? $sql;

        // Backticks → double quotes
        $sql = preg_replace_callback('/`([^`]+)`/', static fn ($m) => '"'.$m[1].'"', $sql) ?? $sql;

        $sql = preg_replace('/\bbigint\(\d+\)\s+unsigned/i', 'BIGINT', $sql) ?? $sql;
        $sql = preg_replace('/\bint\(\d+\)\s+unsigned/i', 'INTEGER', $sql) ?? $sql;
        $sql = preg_replace('/\bsmallint\(\d+\)\s+unsigned/i', 'SMALLINT', $sql) ?? $sql;
        $sql = preg_replace('/\btinyint\(\d+\)\s+unsigned/i', 'SMALLINT', $sql) ?? $sql;
        $sql = preg_replace('/\bbigint\(\d+\)/i', 'BIGINT', $sql) ?? $sql;
        $sql = preg_replace('/\bint\(\d+\)/i', 'INTEGER', $sql) ?? $sql;
        $sql = preg_replace('/\bsmallint\(\d+\)/i', 'SMALLINT', $sql) ?? $sql;
        $sql = preg_replace('/\btinyint\(1\)/i', 'BOOLEAN', $sql) ?? $sql;
        $sql = preg_replace('/\btinyint\(\d+\)/i', 'SMALLINT', $sql) ?? $sql;
        $sql = preg_replace('/\bmediumint\(\d+\)/i', 'INTEGER', $sql) ?? $sql;
        $sql = preg_replace('/\bdouble\b/i', 'DOUBLE PRECISION', $sql) ?? $sql;
        $sql = preg_replace('/\blongtext\b/i', 'TEXT', $sql) ?? $sql;
        $sql = preg_replace('/\bmediumtext\b/i', 'TEXT', $sql) ?? $sql;
        $sql = preg_replace('/\btinytext\b/i', 'TEXT', $sql) ?? $sql;
        $sql = preg_replace('/\blongblob\b/i', 'BYTEA', $sql) ?? $sql;
        $sql = preg_replace('/\bmediumblob\b/i', 'BYTEA', $sql) ?? $sql;
        $sql = preg_replace('/\bblob\b/i', 'BYTEA', $sql) ?? $sql;
        $sql = preg_replace('/\bdatetime\b/i', 'TIMESTAMP', $sql) ?? $sql;
        $sql = preg_replace('/\benum\s*\([^)]+\)/i', 'VARCHAR(255)', $sql) ?? $sql;
        $sql = preg_replace('/\bset\s*\([^)]+\)/i', 'TEXT', $sql) ?? $sql;
        $sql = preg_replace('/\bjson\b/i', 'JSONB', $sql) ?? $sql;

        // AUTO_INCREMENT primary keys (id and other single-column cases)
        $sql = preg_replace(
            '/("[\w]+"\s+BIGINT)\s+NOT\s+NULL\s+AUTO_INCREMENT/i',
            '$1 GENERATED BY DEFAULT AS IDENTITY NOT NULL',
            $sql
        ) ?? $sql;
        $sql = preg_replace('/\bAUTO_INCREMENT\b/i', '', $sql) ?? $sql;

        // MySQL ON UPDATE current_timestamp — drop (Postgres needs triggers)
        $sql = preg_replace('/\s+ON\s+UPDATE\s+current_timestamp\(\)/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bcurrent_timestamp\(\)/i', 'CURRENT_TIMESTAMP', $sql) ?? $sql;
        $sql = preg_replace("/DEFAULT\s+'0000-00-00(?: 00:00:00)?'/i", 'DEFAULT NULL', $sql) ?? $sql;

        // UNIQUE KEY / KEY → UNIQUE / drop secondary indexes from CREATE TABLE
        $sql = preg_replace('/,\s*UNIQUE KEY\s+"[^"]+"\s*\(/i', ', UNIQUE (', $sql) ?? $sql;
        $sql = preg_replace('/,\s*UNIQUE INDEX\s+"[^"]+"\s*\(/i', ', UNIQUE (', $sql) ?? $sql;
        $sql = preg_replace('/,\s*KEY\s+"[^"]+"\s*\([^)]+\)/i', '', $sql) ?? $sql;
        $sql = preg_replace('/,\s*INDEX\s+"[^"]+"\s*\([^)]+\)/i', '', $sql) ?? $sql;
        $sql = preg_replace('/,\s*FULLTEXT KEY\s+"[^"]+"\s*\([^)]+\)/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\s+USING\s+BTREE/i', '', $sql) ?? $sql;

        // CONSTRAINT names can stay; UNSIGNED leftover; boolean defaults
        $sql = preg_replace('/\bUNSIGNED\b/i', '', $sql) ?? $sql;
        $sql = preg_replace('/\bBOOLEAN\s+NOT\s+NULL\s+DEFAULT\s+1\b/i', 'BOOLEAN NOT NULL DEFAULT TRUE', $sql) ?? $sql;
        $sql = preg_replace('/\bBOOLEAN\s+NOT\s+NULL\s+DEFAULT\s+0\b/i', 'BOOLEAN NOT NULL DEFAULT FALSE', $sql) ?? $sql;
        $sql = preg_replace('/\bBOOLEAN\s+DEFAULT\s+1\b/i', 'BOOLEAN DEFAULT TRUE', $sql) ?? $sql;
        $sql = preg_replace('/\bBOOLEAN\s+DEFAULT\s+0\b/i', 'BOOLEAN DEFAULT FALSE', $sql) ?? $sql;

        // Clean double commas / trailing commas before )
        $sql = preg_replace('/,\s*,/', ',', $sql) ?? $sql;
        $sql = preg_replace('/,\s*\)/', ')', $sql) ?? $sql;

        return trim($sql)."\n";
    }
}
