<?php

namespace Tests\Feature;

use App\Domain\Installer\PostgresSchemaTranslator;
use Tests\TestCase;

class PostgresSchemaTranslatorTest extends TestCase
{
    public function test_translates_core_mysql_constructs(): void
    {
        $mysql = <<<'SQL'
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS `__DB_PREFIX__products` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `sku` varchar(255) NOT NULL,
  `is_enabled` tinyint(1) NOT NULL DEFAULT 1,
  `price` double DEFAULT NULL,
  `body` longtext,
  `started_at` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  PRIMARY KEY (`id`),
  KEY `__DB_PREFIX__products_sku_index` (`sku`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
SQL;

        $pgsql = PostgresSchemaTranslator::translate($mysql);

        $this->assertStringNotContainsString('ENGINE=', $pgsql);
        $this->assertStringNotContainsString('AUTO_INCREMENT', $pgsql);
        $this->assertStringNotContainsString('tinyint', strtolower($pgsql));
        $this->assertStringContainsString('GENERATED BY DEFAULT AS IDENTITY', $pgsql);
        $this->assertStringContainsString('BOOLEAN', $pgsql);
        $this->assertStringContainsString('"__DB_PREFIX__products"', $pgsql);
        $this->assertStringNotContainsString('ON UPDATE', $pgsql);
    }

    public function test_full_mysql_schema_translates_without_mysql_only_tokens(): void
    {
        $path = database_path('schema/mysql-schema.sql');
        $this->assertFileExists($path);
        $raw = file_get_contents($path);
        $this->assertIsString($raw);
        $pgsql = PostgresSchemaTranslator::translate($raw);

        preg_match_all('/CREATE TABLE/i', $raw, $mysqlTables);
        preg_match_all('/CREATE TABLE/i', $pgsql, $pgTables);
        $this->assertSame(count($mysqlTables[0]), count($pgTables[0]));
        $this->assertGreaterThan(50, count($pgTables[0]));
        $this->assertStringNotContainsString('ENGINE=InnoDB', $pgsql);
        $this->assertStringNotContainsString('AUTO_INCREMENT', $pgsql);
        $this->assertDoesNotMatchRegularExpression('/\btinyint\s*\(/i', $pgsql);
    }
}
