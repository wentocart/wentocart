<?php

/**
 * Rebuild database/schema/*.sql from the current Laravel migrations.
 *
 *   php package/rebuild-install-schema.php
 */

$root = dirname(__DIR__);
$schemaDir = $root.DIRECTORY_SEPARATOR.'database'.DIRECTORY_SEPARATOR.'schema';
if (! is_dir($schemaDir)) {
    mkdir($schemaDir, 0777, true);
}

$php = PHP_BINARY;
$artisan = $root.DIRECTORY_SEPARATOR.'artisan';

function ran(string $php, string $artisan, array $env, array $args): void
{
    $cmd = array_merge([$php, $artisan], $args);
    $descriptors = [
        1 => ['pipe', 'w'],
        2 => ['pipe', 'w'],
    ];
    $process = proc_open($cmd, $descriptors, $pipes, dirname($artisan), $env);
    if (! is_resource($process)) {
        throw new RuntimeException('Could not start artisan');
    }
    $out = stream_get_contents($pipes[1]);
    $err = stream_get_contents($pipes[2]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $code = proc_close($process);
    if ($code !== 0) {
        fwrite(STDERR, $out.$err);
        throw new RuntimeException('artisan failed: '.implode(' ', $args));
    }
}

function envFor(array $overlay): array
{
    $env = [];
    foreach ($_SERVER as $key => $value) {
        if (is_string($key) && is_string($value) && preg_match('/^[A-Z_][A-Z0-9_]*$/', $key)) {
            $env[$key] = $value;
        }
    }
    foreach ($overlay as $key => $value) {
        $env[$key] = $value;
    }

    return $env;
}

fwrite(STDOUT, "SQLite migrate:fresh (for PHPUnit dump)…\n");
$sqlitePath = $schemaDir.DIRECTORY_SEPARATOR.'_build.sqlite';
@unlink($sqlitePath);

ran($php, $artisan, envFor([
    'APP_ENV' => 'testing',
    'APP_DEBUG' => 'true',
    'WENTO_INSTALLED' => 'false',
    'DB_CONNECTION' => 'sqlite',
    'DB_DATABASE' => $sqlitePath,
    'DB_PREFIX' => '',
    'DB_URL' => '',
    'CACHE_STORE' => 'array',
    'SESSION_DRIVER' => 'array',
    'QUEUE_CONNECTION' => 'sync',
]), ['migrate:fresh', '--force']);

$pdo = new PDO('sqlite:'.$sqlitePath, null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$lines = [
    '-- WentoCart PHPUnit schema (SQLite). Regenerated by package/rebuild-install-schema.php.',
    'PRAGMA foreign_keys=OFF;',
];
$stmt = $pdo->query("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, name");
foreach ($stmt as $row) {
    $sql = trim((string) $row['sql']);
    if ($sql === '') {
        continue;
    }
    $lines[] = rtrim($sql, ';').';';
}
$lines[] = 'PRAGMA foreign_keys=ON;';
$sqliteOut = $schemaDir.DIRECTORY_SEPARATOR.'sqlite-schema.sql';
file_put_contents($sqliteOut, implode("\n", $lines)."\n");
$sql = str_replace('WENTO_', '', (string) file_get_contents($sqliteOut));
file_put_contents($sqliteOut, $sql);
$pdo = null;
@unlink($sqlitePath);
fwrite(STDOUT, 'Wrote '.$sqliteOut.' ('.filesize($sqliteOut)." bytes)\n");

$host = getenv('DB_HOST') ?: '127.0.0.1';
$port = getenv('DB_PORT') ?: '33306';
$user = getenv('DB_USERNAME') !== false ? getenv('DB_USERNAME') : 'root';
$pass = getenv('DB_PASSWORD') !== false ? getenv('DB_PASSWORD') : '';
$throwaway = 'wento_schema_src';
$prefix = 'WENTO_';

// Prefer the shop .env for MySQL host/user when this process did not inherit them.
$dotenv = $root.DIRECTORY_SEPARATOR.'.env';
if (is_file($dotenv)) {
    foreach (file($dotenv, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
        if (! str_contains($line, '=') || str_starts_with(trim($line), '#')) {
            continue;
        }
        [$k, $v] = explode('=', $line, 2);
        $k = trim($k);
        $v = trim($v, " \t\"'");
        if ($k === 'DB_HOST' && $v !== '') {
            $host = $v;
        }
        if ($k === 'DB_PORT' && $v !== '') {
            $port = $v;
        }
        if ($k === 'DB_USERNAME') {
            $user = $v;
        }
        if ($k === 'DB_PASSWORD') {
            $pass = $v;
        }
    }
}

fwrite(STDOUT, "MySQL throwaway migrate:fresh on {$host}:{$port}/{$throwaway}…\n");
$admin = new PDO("mysql:host={$host};port={$port};charset=utf8mb4", $user, $pass, [
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
]);
$admin->exec('DROP DATABASE IF EXISTS `'.$throwaway.'`');
$admin->exec('CREATE DATABASE `'.$throwaway.'` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');

ran($php, $artisan, envFor([
    'APP_ENV' => 'testing',
    'APP_DEBUG' => 'true',
    'WENTO_INSTALLED' => 'false',
    'DB_CONNECTION' => 'mysql',
    'DB_HOST' => $host,
    'DB_PORT' => (string) $port,
    'DB_DATABASE' => $throwaway,
    'DB_USERNAME' => $user,
    'DB_PASSWORD' => $pass,
    'DB_PREFIX' => rtrim($prefix, '_'),
    'DB_URL' => '',
    'CACHE_STORE' => 'array',
    'SESSION_DRIVER' => 'array',
    'QUEUE_CONNECTION' => 'sync',
]), ['migrate:fresh', '--force']);

$dump = [
    $php,
    $root.DIRECTORY_SEPARATOR.'package'.DIRECTORY_SEPARATOR.'dump-install-schema.php',
    '--host='.$host,
    '--port='.$port,
    '--user='.$user,
    '--password='.$pass,
    '--database='.$throwaway,
    '--prefix='.$prefix,
];
passthru(implode(' ', array_map('escapeshellarg', $dump)), $dumpCode);
$admin->exec('DROP DATABASE IF EXISTS `'.$throwaway.'`');
if ($dumpCode !== 0) {
    throw new RuntimeException('dump-install-schema.php failed');
}

fwrite(STDOUT, "Schema dumps are current. Safe to delete database/migrations/*.php\n");
